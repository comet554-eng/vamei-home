  const CJK = /[　-〿㐀-鿿豈-﫿＀-￯]/;
  const SKIP = "script,style,svg,textarea,noscript,[data-i18n-skip]";
  const ATTRS = ["placeholder", "title", "aria-label"];
  const KEY = "mb-lang";
  const norm = (s) => s.replace(/\s+/g, " ").trim();

  function tr(s) {
    if (!CJK.test(s)) return s;
    if (Object.prototype.hasOwnProperty.call(WORDS, s)) return WORDS[s];
    for (const [re, to] of PATTERNS) {
      const m = s.match(re);
      if (m) return to.replace(/\$(t?)(\d)/g, (_, t, n) => {
        const g = m[n] || "";
        return t ? tr(g) ?? g : g;
      });
    }
    return null;
  }

  const pick = (v) => (v === "en" || String(v || "").toLowerCase().startsWith("en") ? "en" : "zh");
