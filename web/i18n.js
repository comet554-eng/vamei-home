  // 文本节点：{zh 原文, shown 最近一次写进去的文字}。节点内容不等于 shown，说明被别的脚本改过，重新记原文。
  const texts = new WeakMap();
  const attrs = new WeakMap();

  function swap(raw, saved, write) {
    if (saved && raw === saved.shown) {
      const want = isEn() ? saved.en : saved.zh;
      if (want !== raw) { saved.shown = want; write(want); }
      return saved;
    }
    if (!CJK.test(raw)) return null; // 新内容不含中文（英文或数据），不用管
    const key = norm(raw), en = tr(key);
    if (en == null || en === key) return null;
    const lead = raw.match(/^\s*/)[0], tail = raw.match(/\s*$/)[0];
    const item = { zh: raw, en: lead + en + tail, shown: raw };
    if (isEn()) { item.shown = item.en; write(item.en); }
    return item;
  }

  function doText(node) {
    const saved = swap(node.data, texts.get(node), (v) => { node.data = v; });
    saved ? texts.set(node, saved) : texts.delete(node);
  }

  function doAttrs(el) {
    let map = attrs.get(el);
    for (const name of ATTRS) {
      if (!el.hasAttribute(name)) continue;
      const saved = swap(el.getAttribute(name), map?.[name], (v) => el.setAttribute(name, v));
      if (saved) (map ||= {})[name] = saved;
      else if (map) delete map[name];
    }
    if (map) attrs.set(el, map);
  }

  // 没写 value 的 <option> 用文字当值，先把中文值钉住，app.js 读到的还是中文
  function pinOption(el) {
    if (el.tagName === "OPTION" && !el.hasAttribute("value") && CJK.test(el.textContent)) el.value = el.textContent;
  }

  const skipped = (el) => !el || !!el.closest(SKIP);

  function walk(root) {
    if (root.nodeType === Node.TEXT_NODE) {
      if (!skipped(root.parentElement)) doText(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE || skipped(root)) return;
    markData(root);
    const it = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
      acceptNode: (n) => (n.nodeType === Node.ELEMENT_NODE && n.matches(SKIP) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    for (let n = it.currentNode; n; n = it.nextNode()) {
      if (n.nodeType === Node.TEXT_NODE) doText(n);
      else { pinOption(n); doAttrs(n); }
    }
  }

